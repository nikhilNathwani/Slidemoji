// Strip variation selectors (U+FE0F, U+FE0E) for normalized comparison
function normalize(emoji) {
	return emoji.replace(/[\uFE0F\uFE0E]/g, "");
}

// Load our corpus
const calendarPath = join(__dirname, "../data/emoji_calendar.json");
const calendar = JSON.parse(readFileSync(calendarPath, "utf8"));
const ourEmojis = calendar.map((e) => normalize(e.emoji));
const ourSet = new Set(ourEmojis);

// Normalize Wikipedia list
const wikiSet = new Set(WIKIPEDIA_SINGLE_EMOJIS.map(normalize));

// 1. In Wikipedia but NOT in our corpus
const missingFromOurs = [...wikiSet].filter((e) => !ourSet.has(e));
// 2. In our corpus but NOT in Wikipedia (i.e. ZWJ sequences, multi-codepoint, etc.)
const notInWiki = [...ourSet].filter((e) => !wikiSet.has(e));

// Helper: show codepoints for debugging
function showCodepoints(emoji) {
	return [...emoji]
		.map(
			(c) =>
				`U+${c.codePointAt(0).toString(16).toUpperCase().padStart(4, "0")}`,
		)
		.join(" ");
}

console.log(`\nWikipedia single emoji count : ${wikiSet.size}`);
console.log(`Our corpus count             : ${ourSet.size}`);
console.log(`\n════════════════════════════════════════════════════════════`);
console.log(
	`IN WIKIPEDIA but MISSING FROM OUR CORPUS (${missingFromOurs.length}):`,
);
console.log(`════════════════════════════════════════════════════════════`);
for (const e of missingFromOurs) {
	console.log(`  ${e}  ${showCodepoints(e)}`);
}

console.log(`\n════════════════════════════════════════════════════════════`);
console.log(
	`IN OUR CORPUS but NOT A SINGLE UNICODE EMOJI (${notInWiki.length}):`,
);
console.log(
	`(These are likely ZWJ sequences, keycap sequences, or multi-codepoint emojis)`,
);
console.log(`════════════════════════════════════════════════════════════`);
for (const e of notInWiki.sort()) {
	const entry = calendar.find((c) => normalize(c.emoji) === e);
	console.log(`  ${e}  ${showCodepoints(e)}  "${entry?.name ?? "?"}"`);
}
